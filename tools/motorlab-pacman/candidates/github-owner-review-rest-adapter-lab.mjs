// Pac-Man Approval Bridge: isolated GitHub REST adapter, LAB SOURCE-ONLY.
// No credential enrollment, token persistence, routes, deployment or network
// call occurs by importing/constructing this module. The existing protected
// GitHub environment stays in force. Only an explicitly trusted owner-host
// may inject a short-lived, user-scoped credential at runtime.
const BASE="https://api.github.com/repos/Br174/Chatgpt";
const OWNER_LOGIN="Br174";
const OWNER_ID=202558590;
const POS=n=>Number.isSafeInteger(n)&&n>0;
const deny=code=>{throw Error("PACMAN_GITHUB_OWNER_REST_HOLD_"+code)};
const responseTypes=new Set(["object","string"]);
const exactRepo=r=>{if(r!=="Br174/Chatgpt")deny("REPOSITORY_DENIED")};
const runId=n=>{if(!POS(n))deny("RUN_ID_INVALID");return n};
const sha=s=>{if(typeof s!=="string"||!/^[0-9a-f]{40}$/.test(s))deny("SHA_INVALID");return s};
const request=async(fetchImpl,accessToken,route,method="GET",body)=>{
 const url=route.startsWith("/user")?"https://api.github.com/user":BASE+route;
 // route is generated by this module exclusively, NEVER user input.
 const init={method,redirect:"manual",headers:{
  accept:"application/vnd.github+json",
  authorization:"Bearer "+accessToken,
  "X-GitHub-Api-Version":"2022-11-28",
  "user-agent":"motorlab-pacman-owner-review-lab"
 }};
 if(body!==undefined){
  init.headers["content-type"]="application/json";
  init.body=JSON.stringify(body);
 }
 let res;
 try{res=await fetchImpl(url,init);}catch{deny("NETWORK_UNKNOWN_NO_RETRY")}
 // Fail closed on redirects, 401, 403, 404, 429, 5xx and malformed responses.
 if(res?.status!==200)deny(method==="POST"?"APPROVAL_UNCONFIRMED_NO_RETRY":"GITHUB_READ_FAILED");
 let data;try{data=await res.json();}catch{deny("GITHUB_RESPONSE_INVALID")}
 if(data===null||(!Array.isArray(data)&&typeof data!=="object"))
  deny("GITHUB_RESPONSE_INVALID");
 return data;
};

/**
 * Construct ONLY in a trusted HTTPS owner-host after out-of-band user OAuth.
 * This is NOT a ChatGPT tool, OAuth authorization server, user authenticator
 * or deployment reviewer. No token belongs in chat, GitHub repository, JSON
 * request, GitHub Actions env/secrets, or source code.
 *
 * getOwnerAccessToken must be a trusted closure and MUST return an owner-user
 * OAuth token with required Deployments:write + Actions:read + Contents:read.
 * GitHub is final authority on pending deployment eligibility.
 */
export function createOwnerReviewGitHubRestLab({getOwnerAccessToken,fetchImpl}={}){
 if(typeof getOwnerAccessToken!=="function"||typeof fetchImpl!=="function")
  deny("TRUSTED_OWNER_TRANSPORT_NOT_CONNECTED");
 let token;
 async function ownerToken(){
  if(typeof token!=="string"){
   try{token=await getOwnerAccessToken();}catch{deny("OWNER_OAUTH_UNAVAILABLE")}
  }
  if(typeof token!=="string"||token.length<24||/[\r\n\s]/.test(token))
   deny("OWNER_OAUTH_UNAVAILABLE");
  return token;
 }
 const read=async(route)=>request(fetchImpl,await ownerToken(),route);
 return Object.freeze({
  async getAuthenticatedUser(){
   const j=await read("/user");
   if(j.login!==OWNER_LOGIN||j.id!==OWNER_ID||j.type!=="User")
    deny("REVIEWER_IDENTITY_UNVERIFIED");
   return Object.freeze({login:j.login,id:j.id});
  },
  async getRun({repository,runId:id}={}){
   exactRepo(repository);
   const j=await read("/actions/runs/"+runId(id));
   return j;
  },
  async getCommit({repository,sha:ref}={}){
   exactRepo(repository);
   return read("/commits/"+sha(ref));
  },
  async getPendingDeployments({repository,runId:id}={}){
   exactRepo(repository);
   const a=await read("/actions/runs/"+runId(id)+"/pending_deployments");
   if(!Array.isArray(a)||a.length>20)deny("PENDING_RESPONSE_INVALID");
   return a;
  },
  async reviewPendingDeployments({repository,runId:id,environment_ids,state,comment}={}){
   exactRepo(repository);runId(id);
   if(!Array.isArray(environment_ids)||environment_ids.length!==1||
      !POS(environment_ids[0])||state!=="approved"||
      typeof comment!=="string"||
      !/^Pac-Man owner-reviewed read-only request-[0-9]{8}-[0-9]{3}$/.test(comment))
    deny("REVIEW_SCOPE_DENIED");
   const body={environment_ids:[environment_ids[0]],state,comment};
   // A single POST, never retried. This provider is called ONLY after the
   // existing cryptographic attestation and exact-run checks in reviewer LAB.
   await request(fetchImpl,await ownerToken(),
    "/actions/runs/"+id+"/pending_deployments","POST",body);
   return {status:200};
  },
  async getReviewHistory({repository,runId:id}={}){
   exactRepo(repository);
   const a=await read("/actions/runs/"+runId(id)+"/approvals");
   if(!Array.isArray(a)||a.length>100)deny("APPROVAL_HISTORY_INVALID");
   return a;
  }
 });
}
